export function getCardById(id: number): TarotCard | undefined {
  return TAROT_DECK.find(c => c.id === id);
}

export function getRandomTarotCard(excludeIds: number[] = []): TarotCard {
  const available = TAROT_DECK.filter(c => !excludeIds.includes(c.id));
  const pool = available.length > 0 ? available : TAROT_DECK;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
